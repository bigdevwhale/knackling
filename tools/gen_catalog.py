"""Writes app/src/main/java/app/knackling/domain/Catalog.kt from tools/hobbies.py and tools/ideas.py.

    python tools/gen_catalog.py
"""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "tools"))
from hobbies import GROUPS, UNITS, HOBBIES, OWN  # noqa: E402
from ideas import IDEAS, IDEAS_OWN  # noqa: E402

COLORS = {
    "guitar": 0xC8642A, "piano": 0x4A4A5C, "singing": 0xE2B93B, "drums": 0xB5452E, "violin": 0xA8672F,
    "drawing": 0x7D8590, "watercolor": 0x6FA8D6, "painting": 0xD9534F, "calligraphy": 0x2F3E5C, "digital": 0x3FB8C2, "photo": 0x6E6A86,
    "embroidery": 0xD4607A, "knitting": 0xDDA020, "crochet": 0xEE93B0, "sewing": 0x9A7FB8,
    "pottery": 0xC27447, "woodwork": 0xA97A43, "beading": 0x4E9CC9, "origami": 0xD98CA0, "models": 0x6B8BA4, "candles": 0xE9BE5C, "journal": 0xA98BD6,
    "reading": 0x8D5B3A, "writing": 0x34528F, "languages": 0xE05A3A,
    "chess": 0x505050, "puzzles": 0xE3913B,
    "garden": 0x6FA34A, "fishing": 0x3F7FB5, "birding": 0x8C8C6A, "mushrooms": 0x8B5A2B,
    "dance": 0xEE7898, "yoga": 0x9C84CC, "cycling": 0xCDA85E, "climbing": 0x8FA0AC,
    "cooking": 0xC9773D, "baking": 0xCF9354,
    "coding": 0x3FA874, "electronics": 0xEE9E2E, "astronomy": 0x2D3E7A,
}
OWN_COLORS = {
    "ember": 0xE08A3C, "puff": 0x7F95B0, "mint": 0x7CC9A6, "lilac": 0xB79AD8, "nugget": 0xE3B04B, "frost": 0xB9CCD8, "peach": 0xF2A487,
    "capy": 0xC59A63, "griff": 0x3EA6A0, "cloud": 0x9AA0A8, "tanuki": 0xC0703A, "sky": 0x86BCE8, "coral": 0xE2624E, "leo": 0xB8B0A0, "chip": 0xB57A45,
}


def q(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("$", "\\$") + '"'


def main():
    out = ["package app.knackling.domain", "",
           "// Generated by tools/gen_catalog.py from tools/hobbies.py and tools/ideas.py – edit those, not this file.", "",
           "object Catalog {"]
    out.append("    val groups = listOf(")
    for k, (ru, en) in GROUPS.items():
        out.append(f"        Group({q(k)}, {q(ru)}, {q(en)}),")
    out.append("    )")
    out.append("    val units = mapOf(")
    for k, v in UNITS.items():
        out.append(f"        {q(k)} to Unit({q(k)}, {', '.join(q(x) for x in v)}),")
    out.append("    )")
    out.append("    val kinds = listOf(")
    for k, v in HOBBIES.items():
        group, ru, en, unit, pru, pen = v[:6]
        ideas = ", ".join(f"Idea({q(a)}, {q(b)})" for a, b in IDEAS[k])
        out.append(f"        Kind({q(k)}, {q(group)}, {q(ru)}, {q(en)}, {q(unit) if unit else 'null'}, {q(pru)}, {q(pen)}, 0x{COLORS[k]:06X}, listOf({ideas})),")
    out.append("    )")
    out.append("    val own = listOf(")
    for k, (pru, pen, _) in OWN.items():
        out.append(f"        OwnPet({q('own_' + k)}, {q(pru)}, {q(pen)}, 0x{OWN_COLORS[k]:06X}),")
    out.append("    )")
    out.append("    val ownIdeas = listOf(" + ", ".join(f"Idea({q(a)}, {q(b)})" for a, b in IDEAS_OWN) + ")")
    out.append("}")
    dst = ROOT / "app/src/main/java/app/knackling/domain/Catalog.kt"
    dst.parent.mkdir(parents=True, exist_ok=True)
    dst.write_text("\n".join(out) + "\n", encoding="utf-8")
    print("wrote", dst, len(HOBBIES), "hobbies", len(OWN), "own")


if __name__ == "__main__":
    main()
